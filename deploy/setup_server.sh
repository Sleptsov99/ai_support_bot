#!/usr/bin/env bash
# One-time server setup (Ubuntu/Debian). Run on the server as root:  bash setup_server.sh
set -euo pipefail
DOMAIN=ai.avalink.co
APP_DIR=/opt/ai_support_bot

apt-get update
apt-get install -y ca-certificates curl rsync nginx certbot python3-certbot-nginx apache2-utils ufw

if ! command -v docker >/dev/null; then
    curl -fsSL https://get.docker.com | sh
fi
systemctl enable --now docker nginx

ufw allow OpenSSH
ufw allow 'Nginx Full'
ufw --force enable

# The domain is behind Cloudflare: take the real client IP from CF-Connecting-IP (rate limit per user, not per CF node).
{
    echo "# Cloudflare ranges, generated by setup_server.sh"
    for ip in $(curl -fsS https://www.cloudflare.com/ips-v4) $(curl -fsS https://www.cloudflare.com/ips-v6); do
        echo "set_real_ip_from $ip;"
    done
    echo "real_ip_header CF-Connecting-IP;"
} > /etc/nginx/conf.d/cloudflare-realip.conf
nginx -t && systemctl reload nginx

mkdir -p "$APP_DIR"
echo "Done. Next: copy the project to $APP_DIR (deploy/deploy.sh from your laptop), then follow DEPLOY.md step 4."
